// Writes a migration that imports content/questions.json into the questions table as approved.
// Usage: node scripts/gen-starter-migration.mjs <timestamp>_<slug>
// Applied migrations must never be edited, so later changes to the starter set need a new migration.

import { readFileSync, writeFileSync } from 'node:fs';

const name = process.argv[2];
if (!/^\d+_[a-z0-9_-]+$/.test(name ?? '')) {
  console.error('Usage: node scripts/gen-starter-migration.mjs <timestamp>_<slug>');
  process.exit(1);
}

const { questions } = JSON.parse(readFileSync(new URL('../content/questions.json', import.meta.url), 'utf8'));

const str = (s) => `'${s.replace(/'/g, "''")}'`;
const arr = (items) => `ARRAY[${items.map(str).join(', ')}]::TEXT[]`;

const rows = questions.map(
  (q) => `  (${str(q.id)}, ${str(q.text)}, ${arr(q.topics)}, ${arr(q.situations)}, ${str(q.intensity)}, 'approved', NOW())`,
);

const sql = `-- Generated by scripts/gen-starter-migration.mjs from content/questions.json. Do not edit once applied.
INSERT INTO questions (id, text, topics, situations, intensity, status, reviewed_at) VALUES
${rows.join(',\n')}
ON CONFLICT (id) DO NOTHING;
`;

const out = new URL(`../netlify/database/migrations/${name}.sql`, import.meta.url);
writeFileSync(out, sql);
console.log(`Wrote ${questions.length} questions to ${out.pathname}`);
